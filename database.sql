-- 1. Create the Donors Table
CREATE TABLE DONORS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(100),
    AGE NUMBER,
    PHONE VARCHAR2(15),
    CITY VARCHAR2(100),
    BLOOD_GROUP VARCHAR2(5),
    LATITUDE NUMBER,
    LONGITUDE NUMBER,
    CERTIFICATE VARCHAR2(255)
);

